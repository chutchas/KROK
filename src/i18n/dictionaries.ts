/** แทนที่ตัวแปรในสตริง เช่น tt("forms.stepsFields", {steps:3, fields:9}) */
export function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
